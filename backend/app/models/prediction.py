"""ORM model — predictions table.

Stores the machine learning prediction result, SHAP explanation, and the
synthesised risk score for one application pipeline run.
"""

from __future__ import annotations

import enum
import uuid
from typing import TYPE_CHECKING, Any, Dict, Optional

from sqlalchemy import Boolean, ForeignKey, Numeric, String, Text
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database.base import Base, PgEnum

if TYPE_CHECKING:
    from app.models.application import Application


class ModelUsed(str, enum.Enum):
    LOGISTIC_REGRESSION = "logistic_regression"
    RANDOM_FOREST = "random_forest"
    XGBOOST = "xgboost"
    ENSEMBLE = "ensemble"


class PredictionOutcome(str, enum.Enum):
    LOW_RISK = "low_risk"       # unlikely to default
    HIGH_RISK = "high_risk"     # likely to default


class RiskLevel(str, enum.Enum):
    VERY_LOW = "very_low"    # 0–20
    LOW = "low"              # 21–40
    MEDIUM = "medium"        # 41–60
    HIGH = "high"            # 61–80
    VERY_HIGH = "very_high"  # 81–100


class Prediction(Base):
    __tablename__ = "predictions"

    application_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("loan_applications.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    # Model details
    model_used: Mapped[ModelUsed] = mapped_column(
        PgEnum(ModelUsed, name="model_used"), nullable=False
    )
    model_version: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)

    # Core prediction
    probability_of_default: Mapped[float] = mapped_column(
        Numeric(8, 6), nullable=False
    )  # 0.0 – 1.0
    outcome: Mapped[PredictionOutcome] = mapped_column(
        PgEnum(PredictionOutcome, name="prediction_outcome"), nullable=False
    )

    # Risk score (0–100, derived from probability + rule engine context)
    risk_score: Mapped[float] = mapped_column(Numeric(5, 2), nullable=False)
    risk_level: Mapped[RiskLevel] = mapped_column(
        PgEnum(RiskLevel, name="risk_level"), nullable=False
    )

    # SHAP explanation — top contributing features with their SHAP values
    shap_values: Mapped[Optional[Dict[str, Any]]] = mapped_column(JSONB, nullable=True)
    feature_importance: Mapped[Optional[Dict[str, Any]]] = mapped_column(JSONB, nullable=True)

    # Human-readable explanation
    explanation_text: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # Feature values used for this prediction
    input_features: Mapped[Optional[Dict[str, Any]]] = mapped_column(JSONB, nullable=True)

    # Model comparison results (accuracy, precision, recall, F1, ROC-AUC)
    model_metrics: Mapped[Optional[Dict[str, Any]]] = mapped_column(JSONB, nullable=True)

    # Recommendation generated by combining rule engine + ML outcome
    recommendation: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # Whether ML ran or was skipped (mandatory rule failure)
    ml_executed: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    skip_reason: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # Relationship
    application: Mapped["Application"] = relationship(
        "Application", back_populates="predictions"
    )

    def __repr__(self) -> str:
        return (
            f"<Prediction id={self.id} application_id={self.application_id} "
            f"risk={self.risk_score} outcome={self.outcome}>"
        )
